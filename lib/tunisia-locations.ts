export const normalizeGovernorate = (value: string) =>
  value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim();

export const resolveGovernorateName = (value: string): string => {
  const trimmed = value.trim();
  if (!trimmed) {
    return "";
  }

  if (GOVERNORATE_CITIES[trimmed]) {
    return trimmed;
  }

  const normalized = normalizeGovernorate(trimmed);
  return (
    TUNISIAN_GOVERNORATES.find(
      (governorate) => normalizeGovernorate(governorate) === normalized
    ) || trimmed
  );
};

export const getCitiesForGovernorate = (state: string): string[] => {
  const resolvedState = resolveGovernorateName(state);
  return GOVERNORATE_CITIES[resolvedState] || [];
};

